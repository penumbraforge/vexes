import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseLockfile as parseNpm } from '../src/parsers/npm.js';
import { parseLockfile as parsePnpm } from '../src/parsers/pnpm.js';
import { parseLockfile as parseYarn } from '../src/parsers/yarn.js';
import { parseLockfile as parseCargo } from '../src/parsers/cargo.js';
import { parseLockfile as parseRuby } from '../src/parsers/ruby.js';
import { parseLockfile as parsePhp } from '../src/parsers/php.js';
import { parseLockfile as parseNuget } from '../src/parsers/dotnet.js';
import { parseLockfile as parseJava } from '../src/parsers/java.js';
import { parseLockfile as parseHex } from '../src/parsers/hex.js';
import { parseLockfile as parsePub } from '../src/parsers/pub.js';
import { parsePipfileLock, parsePoetryLock } from '../src/parsers/pypi.js';
import { parseManifest as parseGoMod } from '../src/parsers/go.js';

function withFixture(filename, content, fn) {
  const dir = mkdtempSync(join(tmpdir(), 'vexes-lock-schema-'));
  try {
    const path = join(dir, filename);
    writeFileSync(path, content);
    return fn(path);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

const CASES = [
  ['package-lock.json', parseNpm, JSON.stringify({ lockfileVersion: 3, packages: { '': {} } })],
  ['pnpm-lock.yaml', parsePnpm, "lockfileVersion: '9.0'\nsettings: {}\nimporters: {}\npackages: {}\nsnapshots: {}\n"],
  ['yarn.lock', parseYarn, '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n'],
  ['Cargo.lock', parseCargo, '# This file is automatically @generated by Cargo.\nversion = 3\n'],
  ['Gemfile.lock', parseRuby, 'GEM\n  specs:\n\nPLATFORMS\n\nDEPENDENCIES\n'],
  ['composer.lock', parsePhp, JSON.stringify({ packages: [], 'packages-dev': [] })],
  ['packages.lock.json', parseNuget, JSON.stringify({ version: 1, dependencies: {} })],
  ['gradle.lockfile', parseJava, 'empty=\n'],
  ['mix.lock', parseHex, '%{}\n'],
  ['pubspec.lock', parsePub, 'packages:\nsdks:\n  dart: ">=3.0.0 <4.0.0"\n'],
  ['Pipfile.lock', parsePipfileLock, JSON.stringify({ _meta: {}, default: {}, develop: {} })],
  ['poetry.lock', parsePoetryLock, 'package = []\n'],
  ['go.mod', parseGoMod, 'module example.test/empty\n\ngo 1.22\n'],
];

describe('lockfile schema validation', () => {
  it('accepts recognizable, genuinely empty dependency graphs', () => {
    for (const [filename, parser, content] of CASES) {
      const parsed = withFixture(filename, content, parser);
      assert.deepEqual([...parsed], [], `${filename} should be a valid empty graph`);
    }
  });

  it('rejects arbitrary content instead of returning a false-clean empty graph', () => {
    for (const [filename, parser] of CASES) {
      assert.throws(
        () => withFixture(filename, filename.endsWith('.json') || filename.endsWith('.lock') ? '{}' : 'not a lockfile\n', parser),
        undefined,
        `${filename} accepted an unrecognized schema`,
      );
    }
  });

  it('parses representative pnpm v6 and v9 package entries', () => {
    for (const version of ['6.0', '9.0']) {
      const content = `lockfileVersion: '${version}'\npackages:\n  /express@4.18.2:\n    dev: false\n`;
      const parsed = withFixture('pnpm-lock.yaml', content, parsePnpm);
      assert.ok(parsed.some(dep => dep.name === 'express' && dep.version === '4.18.2'));
    }
  });

  it('fails loud on unsupported pnpm v5 keys instead of returning an empty graph', () => {
    const content = "lockfileVersion: '5.4'\npackages:\n  /express/4.18.2:\n    dev: false\n";
    assert.throws(() => withFixture('pnpm-lock.yaml', content, parsePnpm), /unsupported pnpm lockfileVersion/);
  });

  it('excludes replaced Go modules and marks the selected graph incomplete', () => {
    const parsed = withFixture('go.mod', [
      'module example.test/app',
      'go 1.22',
      'require example.test/original v1.2.3',
      'replace example.test/original => ../local-original',
      '',
    ].join('\n'), parseGoMod);
    assert.equal(parsed.some(dep => dep.name === 'example.test/original'), false);
    assert.equal(parsed.unresolvedEntries, 1);
  });

  it('fails source coverage for an applicable go.work and excludes its replacements', () => {
    const dir = mkdtempSync(join(tmpdir(), 'vexes-go-workspace-'));
    const moduleDir = join(dir, 'module');
    mkdirSync(moduleDir, { recursive: true });
    try {
      writeFileSync(join(dir, 'go.work'), [
        'go 1.22',
        'use ./module',
        'replace example.test/clean => ./local-malicious',
        '',
      ].join('\n'));
      writeFileSync(join(moduleDir, 'go.mod'), [
        'module example.test/app',
        'go 1.22',
        'require example.test/clean v1.2.3',
        '',
      ].join('\n'));

      const deps = parseGoMod(join(moduleDir, 'go.mod'));
      assert.equal(deps.some(dep => dep.name === 'example.test/clean'), false);
      assert.ok(deps.unresolvedEntries > 0, 'workspace selection must prevent a complete/clean source claim');
    } finally {
      rmSync(dir, { recursive: true, force: true });
    }
  });
});
