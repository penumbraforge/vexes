import { describe, it } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parseLockfile as parseCargo } from '../src/parsers/cargo.js';
import { parseLockfile as parsePub } from '../src/parsers/pub.js';
import { parseLockfile as parseHex } from '../src/parsers/hex.js';
import { parseLockfile as parseComposerLock, parseManifest as parseComposerManifest } from '../src/parsers/php.js';
import { parseLockfile as parseGemLock } from '../src/parsers/ruby.js';
import { parseLockfile as parseYarn } from '../src/parsers/yarn.js';

function parseFixture(filename, content, parser) {
  const dir = mkdtempSync(join(tmpdir(), 'vexes-source-identity-'));
  try {
    const path = join(dir, filename);
    writeFileSync(path, content);
    return parser(path);
  } finally {
    rmSync(dir, { recursive: true, force: true });
  }
}

function assertUnresolved(deps, expected) {
  assert.equal(deps.unresolvedEntries, expected);
  assert.equal(Object.prototype.propertyIsEnumerable.call(deps, 'unresolvedEntries'), false);
  assert.equal(Object.keys(deps).includes('unresolvedEntries'), false);
}

describe('non-registry source identity', () => {
  it('Cargo emits crates.io only and counts git, path/workspace, and custom registries', () => {
    const deps = parseFixture('Cargo.lock', `# This file is automatically @generated by Cargo.
version = 3

[[package]]
name = "public-crate"
version = "1.2.3"
source = "registry+https://github.com/rust-lang/crates.io-index"

[[package]]
name = "git-crate"
version = "1.2.3"
source = "git+https://github.com/example/git-crate#abc"

[[package]]
name = "private-crate"
version = "1.2.3"
source = "registry+https://crates.example/index"

[[package]]
name = "local-crate"
version = "1.2.3"
`, parseCargo);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public-crate@1.2.3']);
    assertUnresolved(deps, 3);
  });

  it('Pub emits pub.dev only and counts git, path, and custom-hosted entries', () => {
    const deps = parseFixture('pubspec.lock', `packages:
  public_pkg:
    dependency: "direct main"
    description:
      name: public_pkg
      url: "https://pub.dev"
    source: hosted
    version: "1.2.3"
  private_pkg:
    dependency: transitive
    description:
      name: private_pkg
      url: 'https://pub.example'
    source: hosted
    version: "2.0.0"
  git_pkg:
    dependency: transitive
    description:
      url: "https://github.com/example/git_pkg.git"
    source: git
    version: "3.0.0"
  path_pkg:
    dependency: transitive
    description:
      path: "../path_pkg"
    source: path
    version: "4.0.0"
sdks:
  dart: ">=3.0.0 <4.0.0"
`, parsePub);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public_pkg@1.2.3']);
    assertUnresolved(deps, 3);
  });

  it('Hex emits public hexpm releases and counts git/path/custom-repository entries', () => {
    const deps = parseFixture('mix.lock', `%{
  "public_hex": {:hex, :public_hex, "1.2.3", "hash", [:mix], [], "hexpm", "outer", 1, %{}, []},
  "private_hex": {:hex, :private_hex, "2.0.0", "hash", [:mix], [], "private_repo", "outer", 1, %{}, []},
  "git_hex": {:git, "https://github.com/example/git_hex.git", "abcdef", []},
  "path_hex": {:path, "../path_hex", []},
}
`, parseHex);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public_hex@1.2.3']);
    assertUnresolved(deps, 3);
  });

  it('Composer lock emits Packagist-anchored releases and counts VCS/path/custom entries', () => {
    const deps = parseFixture('composer.lock', JSON.stringify({
      packages: [
        {
          name: 'vendor/public', version: 'v1.2.3',
          'notification-url': 'https://packagist.org/downloads/',
          source: { type: 'git', url: 'https://github.com/vendor/public.git' },
          dist: { type: 'zip', url: 'https://api.github.com/repos/vendor/public/zipball/abc' },
        },
        {
          name: 'vendor/vcs-only', version: '1.0.0',
          source: { type: 'git', url: 'https://git.example/vcs-only.git' },
        },
        {
          name: 'vendor/path', version: '1.0.0',
          'notification-url': 'https://packagist.org/downloads/',
          dist: { type: 'path', url: '../path-package' },
        },
        {
          name: 'vendor/private', version: '1.0.0',
          'notification-url': 'https://packages.example/downloads/',
          dist: { type: 'zip', url: 'https://packages.example/private.zip' },
        },
      ],
      'packages-dev': [],
    }), parseComposerLock);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['vendor/public@1.2.3']);
    assertUnresolved(deps, 4);
  });

  it('Composer manifest refuses exact pins when a custom repository can shadow them', () => {
    const deps = parseFixture('composer.json', JSON.stringify({
      repositories: [{ type: 'vcs', url: 'https://git.example/project.git' }],
      require: { 'vendor/project': '1.2.3', php: '^8.3' },
    }), parseComposerManifest);

    assert.deepEqual([...deps], []);
    assertUnresolved(deps, 1);
  });

  it('Gemfile.lock emits canonical RubyGems entries and counts GIT, PATH, and custom GEM sources', () => {
    const deps = parseFixture('Gemfile.lock', `GEM
  remote: https://rubygems.org/
  specs:
    public_gem (1.2.3)

GIT
  remote: https://github.com/example/git_gem.git
  revision: abcdef
  specs:
    git_gem (2.0.0)

PATH
  remote: ../path_gem
  specs:
    path_gem (3.0.0)

GEM
  remote: https://gems.example/
  specs:
    private_gem (4.0.0)

PLATFORMS
  ruby

DEPENDENCIES
  public_gem
  git_gem!
  path_gem!
  private_gem

CHECKSUMS
  public_gem (1.2.3) sha256=aaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaaa
`, parseGemLock);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public_gem@1.2.3']);
    assert.equal(deps[0].isDirect, true);
    assertUnresolved(deps, 3);
  });

  it('Gemfile.lock marks public coordinates unresolved when artifact checksums are absent', () => {
    const deps = parseFixture('Gemfile.lock', `GEM
  remote: https://rubygems.org/
  specs:
    legacy_gem (1.2.3)

PLATFORMS
  ruby

DEPENDENCIES
  legacy_gem
`, parseGemLock);

    assert.deepEqual([...deps], []);
    assertUnresolved(deps, 1);
  });

  it('Yarn v1 emits public npm tarballs and counts custom, git, and file resolutions', () => {
    const deps = parseFixture('yarn.lock', `# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
# yarn lockfile v1

public-pkg@^1.2.0:
  version "1.2.3"
  resolved "https://registry.yarnpkg.com/public-pkg/-/public-pkg-1.2.3.tgz#abc"

private-pkg@^2.0.0:
  version "2.0.0"
  resolved "https://npm.example/private-pkg/-/private-pkg-2.0.0.tgz"

git-pkg@git+https://github.com/example/git-pkg.git:
  version "3.0.0"
  resolved "git+https://github.com/example/git-pkg.git#abc"

path-pkg@file:../path-pkg:
  version "4.0.0"
  resolved "file:../path-pkg"

innocent@^1.0.0:
  version "1.0.0"
  resolved "https://registry.yarnpkg.com/evil/-/evil-9.9.9.tgz#abc"
`, parseYarn);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public-pkg@1.2.3']);
    assertUnresolved(deps, 4);
  });

  it('Yarn Berry emits exact npm coordinates but marks their registry origin unverified', () => {
    const deps = parseFixture('yarn.lock', `__metadata:
  version: 8
  cacheKey: 10c0

"public-pkg@npm:^1.2.0":
  version: 1.2.3
  resolution: "public-pkg@npm:1.2.3"

"git-pkg@git:https://github.com/example/git-pkg.git":
  version: 2.0.0
  resolution: "git-pkg@git:https://github.com/example/git-pkg.git#abc"

"workspace-pkg@workspace:.":
  version: 0.0.0-use.local
  resolution: "workspace-pkg@workspace:."

"patched-pkg@patch:patched-pkg@npm%3A3.0.0#./patch.diff":
  version: 3.0.0
  resolution: "patched-pkg@patch:patched-pkg@npm%3A3.0.0#./patch.diff"

"remote-pkg@https://packages.example/remote.tgz":
  version: 4.0.0
  resolution: "remote-pkg@https://packages.example/remote.tgz"
`, parseYarn);

    assert.deepEqual(deps.map(dep => `${dep.name}@${dep.version}`), ['public-pkg@1.2.3']);
    assert.equal(deps[0].sourceType, 'unknown');
    assertUnresolved(deps, 5);
  });
});
